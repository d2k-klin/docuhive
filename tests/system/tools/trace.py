"""Generate traceability from collected tests; strict mode requires current passing evidence."""

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

from qa_plugin import RESULTS, ROOT, fingerprint

ID = re.compile(
    r"\b(?:QAR-[A-Z]+|STO|ING|MAIL|CAP|DOC|CLS|SRCH|QA|AUTH|AI|WEB|EXT|AUTO|LRN|GUIDE|NFR)-\d+\b"
)


def requirement_ids(text: str) -> set[str]:
    matches = re.findall(r"\*\*([A-Z]+-\d+)\*\*|^\| (NFR-\d+)\b", text, re.M)
    return {left or right for left, right in matches}


def manual_entries(text: str) -> list[dict]:
    entries = []
    for line in text.splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) == 8 and cells[0].startswith("MC-"):
            entries.append(
                dict(
                    zip(
                        (
                            "id",
                            "requirements",
                            "steps",
                            "expected",
                            "date",
                            "environment",
                            "result",
                            "person",
                        ),
                        cells,
                        strict=True,
                    )
                )
            )
    return entries


def render(
    ids: set[str], collected: list[dict], manual: list[dict], evidence: dict
) -> tuple[str, list[str]]:
    lines = [
        "# QA traceability",
        "",
        "Generated by `make qa-trace`. A link is coverage intent, not acceptance.",
        "Only current passing results or dated, named manual signatures count in strict mode.",
        "",
        "| Requirement | Tests / manual check | Type | Status | Last run | Notes |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    uncovered = []
    for req in sorted(ids):
        tests = [t for t in collected if req in t["requirements"]]
        checks = [m for m in manual if req in ID.findall(m["requirements"])]
        outcomes = [evidence.get(t["nodeid"], {}) for t in tests]
        signed = any(
            m["result"] == "passed"
            and re.fullmatch(r"\d{4}-\d{2}-\d{2}", m["date"])
            and m["environment"] not in {"", "pending"}
            and m["person"] not in {"", "pending"}
            for m in checks
        )
        failing = any(o.get("outcome") in {"failed", "error"} for o in outcomes)
        accepted = not failing and (
            signed or bool(tests) and all(o.get("outcome") == "passed" for o in outcomes)
        )
        status = "passed" if accepted else "pending" if tests or checks else "uncovered"
        if not accepted:
            uncovered.append(req)
        links = [f"`{t['nodeid']}`" for t in tests] + [
            f"[{m['id']}](manual-checks.md)" for m in checks
        ]
        kinds = ["automated"] if tests else []
        if checks:
            kinds.append("manual")
        dates = sorted({o["at"] for o in outcomes if "at" in o})
        notes = sorted({t.get("pending", "") for t in tests} - {""})
        lines.append(
            f"| {req} | {'<br>'.join(links) or '—'} | {', '.join(kinds) or '—'} | "
            f"{status} | {dates[-1] if dates else '—'} | {'; '.join(notes)} |"
        )
    return "\n".join(lines) + "\n", uncovered


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--strict", action="store_true")
    args = parser.parse_args()
    ids = requirement_ids((ROOT / "docs/REQUIREMENTS.md").read_text())
    ids.update(ID.findall((ROOT / "docs/Developer-QA/00-requirements.md").read_text()))
    with tempfile.TemporaryDirectory() as folder:
        collected_path = Path(folder) / "collected.json"
        env = dict(os.environ, DOCUHIVE_QA_COLLECTION=str(collected_path))
        run = subprocess.run(
            [sys.executable, "-m", "pytest", "--collect-only", "-q"],
            cwd=ROOT,
            env=env,
            text=True,
            capture_output=True,
        )
        if run.returncode:
            sys.exit(run.stdout + run.stderr)
        collected = json.loads(collected_path.read_text())
    browser = subprocess.run(
        [
            "node",
            "node_modules/@playwright/test/cli.js",
            "test",
            "--config=tests/e2e/playwright.config.ts",
            "--list",
            "--reporter=json",
        ],
        cwd=ROOT,
        text=True,
        capture_output=True,
    )
    if browser.returncode:
        sys.exit(browser.stdout + browser.stderr)

    def visit(suite: dict) -> None:
        for spec in suite.get("specs", []):
            for test in spec["tests"]:
                node = f"{spec['file']}::{spec['title']}[{test['projectName']}]"
                collected.append(
                    {
                        "nodeid": node,
                        "requirements": ID.findall(spec["title"]),
                        "pending": "Browser execution evidence pending",
                    }
                )
        for child in suite.get("suites", []):
            visit(child)

    for suite in json.loads(browser.stdout)["suites"]:
        visit(suite)
    data = json.loads(RESULTS.read_text()) if RESULTS.exists() else {}
    evidence = data.get("tests", {}) if data.get("fingerprint") == fingerprint() else {}
    unknown = {r for test in collected for r in test["requirements"]} - ids
    if unknown:
        sys.exit(f"Unknown requirement IDs: {sorted(unknown)}")
    matrix, uncovered = render(
        ids,
        collected,
        manual_entries((ROOT / "docs/Developer-QA/manual-checks.md").read_text()),
        evidence,
    )
    (ROOT / "docs/Developer-QA/traceability.md").write_text(matrix)
    print(f"{len(ids)} requirements; {len(uncovered)} without current acceptance evidence")
    print("Pending/uncovered: " + ", ".join(uncovered))
    if args.strict and uncovered:
        sys.exit(1)


if __name__ == "__main__":
    main()
